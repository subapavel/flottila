package io.flottila.testkit;

import io.vertx.core.buffer.Buffer;
import io.vertx.core.streams.ReadStream;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.EnumSource;

import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicLong;
import java.util.concurrent.atomic.AtomicReference;
import java.util.function.Consumer;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The hand-over window of the testkit's synchronous streams (FIX-12): a {@code resume()}, {@code fetch()} or
 * {@code endHandler()} from another thread that lands after the drain loop stopped but before it left must be honoured
 * after the current delivery, on the draining thread. The window is staged, not raced: the package-private
 * {@code beforeDrainExit} hook holds the draining thread (this test's own) at the loop exit until the other thread's
 * call has returned. Against the old gating ({@code drain()} returning on {@code draining}) every staged case fails at
 * once on what was delivered — none waits for a timeout.
 */
class DrainHandoverTest {

    /** The two streams with the same drain structure, each built as {@code n} one-byte chunks labelled "1".."n". */
    enum Kind {
        GENERATED {
            @Override ReadStream<Buffer> create(int chunks) { return new GeneratedReadStream(chunks, 1); }
            @Override void beforeDrainExit(ReadStream<Buffer> s, Runnable hook) { ((GeneratedReadStream) s).beforeDrainExit(hook); }
            @Override long delivered(ReadStream<Buffer> s) { return ((GeneratedReadStream) s).delivered(); }
            @Override String label(Buffer chunk) {
                assertEquals(1, chunk.length(), "one-byte chunks");
                for (int i = 0; i < 256; i++) if (GeneratedReadStream.byteAt(i) == chunk.getByte(0)) return String.valueOf(i + 1);
                throw new AssertionError("not a generated byte: " + chunk.getByte(0));
            }
        },
        CHUNKED {
            @Override ReadStream<Buffer> create(int chunks) {
                List<String> parts = new ArrayList<>();
                for (int i = 1; i <= chunks; i++) parts.add(String.valueOf(i));
                return new ChunkedReadStream(parts);
            }
            @Override void beforeDrainExit(ReadStream<Buffer> s, Runnable hook) { ((ChunkedReadStream) s).beforeDrainExit(hook); }
            @Override long delivered(ReadStream<Buffer> s) { return ((ChunkedReadStream) s).delivered(); }
            @Override String label(Buffer chunk) { return chunk.toString(); }
        };

        abstract ReadStream<Buffer> create(int chunks);
        abstract void beforeDrainExit(ReadStream<Buffer> s, Runnable hook);
        abstract long delivered(ReadStream<Buffer> s);
        abstract String label(Buffer chunk);
    }

    /** What happened, in order, and on which thread. */
    record Event(String what, Thread thread) {}

    private final List<Event> events = new CopyOnWriteArrayList<>();

    private List<String> chunksOn(Thread thread) {
        List<String> out = new ArrayList<>();
        for (Event e : events) if (e.what().startsWith("chunk ") && e.thread() == thread) out.add(e.what());
        return out;
    }

    private List<String> all(String prefix) {
        List<String> out = new ArrayList<>();
        for (Event e : events) if (e.what().startsWith(prefix)) out.add(e.what());
        return out;
    }

    private List<String> named(String what) {
        List<String> out = new ArrayList<>();
        for (Event e : events) if (e.what().equals(what)) out.add(e.what());
        return out;
    }

    private int indexOf(String what) {
        for (int i = 0; i < events.size(); i++) if (events.get(i).what().equals(what)) return i;
        return -1;
    }

    /**
     * A hook that, on its first run only, hands {@code call} to a second (platform) thread and holds the draining thread
     * until that call has returned (10 s bound) — the call lands in the window between the loop's stop and its exit.
     */
    private final class Window implements Runnable {
        private final String name;
        private final Consumer<ReadStream<Buffer>> call;
        private final ReadStream<Buffer> stream;
        final AtomicInteger runs = new AtomicInteger();
        final AtomicReference<Thread> drainingThread = new AtomicReference<>();
        final AtomicReference<Thread> other = new AtomicReference<>();

        Window(ReadStream<Buffer> stream, String name, Consumer<ReadStream<Buffer>> call) {
            this.stream = stream;
            this.name = name;
            this.call = call;
        }

        @Override public void run() {
            if (runs.getAndIncrement() > 0) return;
            drainingThread.set(Thread.currentThread());
            CountDownLatch returned = new CountDownLatch(1);
            AtomicReference<Throwable> failure = new AtomicReference<>();
            Thread t = Thread.ofPlatform().name("fix12-other").unstarted(() -> {
                try {
                    call.accept(stream);
                    events.add(new Event(name + " returned", Thread.currentThread()));
                } catch (Throwable e) {
                    failure.set(e);
                } finally {
                    returned.countDown();
                }
            });
            other.set(t);
            t.start();
            try {
                if (!returned.await(10, TimeUnit.SECONDS)) throw new AssertionError(name + " from the other thread never returned");
                if (!t.join(Duration.ofSeconds(10))) throw new AssertionError("the other thread did not finish");
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
                throw new AssertionError(e);
            }
            if (failure.get() != null) throw new AssertionError(name + " from the other thread failed", failure.get());
        }

        void assertStaged(Thread expectedDrainer) {
            assertTrue(runs.get() >= 1, "the hook ran: the window was staged");
            assertSame(expectedDrainer, drainingThread.get(), "the hook ran on the draining thread");
        }
    }

    // A
    @ParameterizedTest
    @EnumSource(Kind.class)
    void aResumeFromAnotherThreadThatLandsAsTheDrainLoopExitsIsHonouredOnTheDrainingThread(Kind kind) {
        Thread test = Thread.currentThread();
        ReadStream<Buffer> s = kind.create(5);
        s.endHandler(v -> events.add(new Event("end", Thread.currentThread())));
        Window window = new Window(s, "resume", ReadStream::resume);
        kind.beforeDrainExit(s, window);
        s.handler(c -> {
            String label = kind.label(c);
            events.add(new Event("chunk " + label, Thread.currentThread()));
            if (label.equals("1")) s.pause();
        });
        window.assertStaged(test);
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3", "chunk 4", "chunk 5"), all("chunk "),
                "the resume that landed in the window was honoured: every chunk delivered, none twice: " + events);
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3", "chunk 4", "chunk 5"), chunksOn(test),
                "chunks 2-5 on the draining (test) thread, not on the resuming one: " + events);
        assertEquals(List.of("end"), named("end"), "the end fired once: " + events);
        assertSame(test, events.get(indexOf("end")).thread(), "the end on the draining thread");
        int resumed = indexOf("resume returned");
        assertTrue(resumed >= 0 && resumed < indexOf("chunk 2"), "the other thread's resume() returned before chunk 2: " + events);
        assertEquals(5, kind.delivered(s));
    }

    // B
    @ParameterizedTest
    @EnumSource(Kind.class)
    void aFetchFromAnotherThreadThatLandsAsTheDrainLoopExitsDeliversExactlyThatManyChunks(Kind kind) {
        Thread test = Thread.currentThread();
        ReadStream<Buffer> s = kind.create(5);
        s.endHandler(v -> events.add(new Event("end", Thread.currentThread())));
        Window window = new Window(s, "fetch(2)", r -> r.fetch(2));
        kind.beforeDrainExit(s, window);
        s.handler(c -> {
            String label = kind.label(c);
            events.add(new Event("chunk " + label, Thread.currentThread()));
            if (label.equals("1")) s.pause();
        });
        window.assertStaged(test);
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3"), all("chunk "),
                "exactly the two fetched chunks followed, then nothing — still paused: " + events);
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3"), chunksOn(test), "on the draining (test) thread: " + events);
        assertEquals(List.of(), named("end"), "no end while paused with chunks left: " + events);
        int fetched = indexOf("fetch(2) returned");
        assertTrue(fetched >= 0 && fetched < indexOf("chunk 2"), "the other thread's fetch returned before chunk 2: " + events);
        assertEquals(3, kind.delivered(s));

        s.resume();
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3", "chunk 4", "chunk 5"), all("chunk "), "a later resume delivers the rest: " + events);
        assertEquals(List.of("end"), named("end"), "and the end, once: " + events);
        assertEquals(5, kind.delivered(s));
    }

    // C
    @ParameterizedTest
    @EnumSource(Kind.class)
    void anEndHandlerSetFromAnotherThreadAsTheDrainLoopExitsFiresOnceOnTheDrainingThread(Kind kind) {
        Thread test = Thread.currentThread();
        ReadStream<Buffer> s = kind.create(2);
        Window window = new Window(s, "endHandler", r -> r.endHandler(v -> events.add(new Event("end", Thread.currentThread()))));
        kind.beforeDrainExit(s, window);
        s.handler(c -> events.add(new Event("chunk " + kind.label(c), Thread.currentThread())));
        window.assertStaged(test);
        assertEquals(List.of("chunk 1", "chunk 2"), all("chunk "), "everything delivered before the window: " + events);
        assertTrue(indexOf("endHandler returned") > indexOf("chunk 2"), "the hook was reached with everything delivered: " + events);
        assertEquals(List.of("end"), named("end"), "the end handler set in the window fired exactly once: " + events);
        assertSame(test, events.get(indexOf("end")).thread(), "on the draining (test) thread, not the setting one");
        assertEquals(2, kind.delivered(s));
    }

    // D
    @ParameterizedTest
    @EnumSource(Kind.class)
    void aHandlerThatResumesFromInsideDoesNotReenterTheDrainLoopNorDeliverTwice(Kind kind) {
        Thread test = Thread.currentThread();
        ReadStream<Buffer> s = kind.create(3);
        AtomicInteger hookRuns = new AtomicInteger();
        s.pause();
        s.endHandler(v -> events.add(new Event("end", Thread.currentThread())));
        kind.beforeDrainExit(s, hookRuns::incrementAndGet);
        AtomicInteger depth = new AtomicInteger();
        AtomicInteger maxDepth = new AtomicInteger();
        s.handler(c -> {
            maxDepth.accumulateAndGet(depth.incrementAndGet(), Math::max);
            events.add(new Event("chunk " + kind.label(c), Thread.currentThread()));
            s.resume();                            // re-entrant: requests a rerun, never a nested delivery
            depth.decrementAndGet();
        });
        assertEquals(List.of(), all("chunk "), "paused before the handler: nothing flows");
        s.fetch(1);
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3"), all("chunk "), "each chunk once, in order: " + events);
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3"), chunksOn(test));
        assertEquals(1, maxDepth.get(), "the handler was never re-entered");
        assertEquals(List.of("end"), named("end"), "the rerun the inner resume requested did not fire the end twice: " + events);
        assertTrue(hookRuns.get() >= 1, "the hook runs at the loop exit");
        assertEquals(3, kind.delivered(s));
        s.resume();
        s.fetch(1);
        assertEquals(List.of("end"), named("end"), "nothing more after the end: " + events);
        assertEquals(3, all("chunk ").size());
    }

    // E
    @ParameterizedTest
    @EnumSource(Kind.class)
    void aFetchOfOneFromAnotherThreadWhilePausedWithNoCreditDeliversExactlyOneMoreChunk(Kind kind) {
        Thread test = Thread.currentThread();
        ReadStream<Buffer> s = kind.create(5);
        s.endHandler(v -> events.add(new Event("end", Thread.currentThread())));
        Window window = new Window(s, "fetch(1)", r -> r.fetch(1));
        kind.beforeDrainExit(s, window);
        s.handler(c -> {
            String label = kind.label(c);
            events.add(new Event("chunk " + label, Thread.currentThread()));
            if (label.equals("1")) s.pause();     // credit 0 from here
        });
        window.assertStaged(test);
        assertEquals(List.of("chunk 1", "chunk 2"), all("chunk "), "exactly one more chunk: " + events);
        assertEquals(List.of("chunk 1", "chunk 2"), chunksOn(test), "on the draining (test) thread: " + events);
        assertEquals(2, kind.delivered(s));
        s.fetch(1);
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3"), all("chunk "), "the credit was left at 0, not corrupted: one fetch, one chunk: " + events);
        assertEquals(List.of(), named("end"));
    }

    // the exception path of the new drain: a throwing handler must not leave the stream "draining" forever
    @ParameterizedTest
    @EnumSource(Kind.class)
    void aHandlerThatThrowsLeavesTheStreamDrainableAgain(Kind kind) {
        ReadStream<Buffer> s = kind.create(3);
        s.endHandler(v -> events.add(new Event("end", Thread.currentThread())));
        AtomicInteger hookRuns = new AtomicInteger();
        kind.beforeDrainExit(s, hookRuns::incrementAndGet);
        boolean[] thrown = {false};
        IllegalStateException boom = assertThrows(IllegalStateException.class, () -> s.handler(c -> {
            events.add(new Event("chunk " + kind.label(c), Thread.currentThread()));
            if (!thrown[0]) {
                thrown[0] = true;
                throw new IllegalStateException("boom");
            }
        }));
        assertEquals("boom", boom.getMessage());
        assertEquals(List.of("chunk 1"), all("chunk "));
        s.resume();
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3"), all("chunk "), "the next resume drains again: " + events);
        assertEquals(List.of("end"), named("end"));
        assertTrue(hookRuns.get() >= 1);
    }

    /**
     * Runs {@code call} on a second (platform) thread from inside a handler and waits for it (10 s bound): a handler
     * invoked under the stream's lock blocks the call on the monitor, and the wait fails with {@code timeoutMessage}.
     * The other thread's failure is rethrown here.
     */
    private static void handOff(String timeoutMessage, Runnable call) {
        CountDownLatch returned = new CountDownLatch(1);
        AtomicReference<Throwable> failure = new AtomicReference<>();
        Thread t = Thread.ofPlatform().name("fix12-other").unstarted(() -> {
            try {
                call.run();
            } catch (Throwable e) {
                failure.set(e);
            } finally {
                returned.countDown();
            }
        });
        t.start();
        try {
            if (!returned.await(10, TimeUnit.SECONDS)) throw new AssertionError(timeoutMessage);
            if (!t.join(Duration.ofSeconds(10))) throw new AssertionError("the other thread did not finish");
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new AssertionError(e);
        }
        if (failure.get() != null) throw new AssertionError("the other thread's call failed", failure.get());
    }

    // G
    @ParameterizedTest
    @EnumSource(Kind.class)
    void theDataHandlerMayHandOffToAnotherThreadThatCallsIntoTheStream(Kind kind) {
        Thread test = Thread.currentThread();
        ReadStream<Buffer> s = kind.create(3);
        s.endHandler(v -> events.add(new Event("end", Thread.currentThread())));
        AtomicLong seen = new AtomicLong(-1);
        s.handler(c -> {
            String label = kind.label(c);
            events.add(new Event("chunk " + label, Thread.currentThread()));
            if (label.equals("1")) handOff("the data handler must not hold the stream's lock", () -> {
                s.pause();
                seen.set(kind.delivered(s));
            });
        });
        assertEquals(1, seen.get(), "the other thread saw chunk 1 counted as delivered");
        assertEquals(List.of("chunk 1"), all("chunk "), "the other thread's pause() stopped delivery after chunk 1: " + events);
        assertEquals(List.of("chunk 1"), chunksOn(test), "on the test thread: " + events);
        assertEquals(List.of(), named("end"), "no end while paused with chunks left: " + events);
        assertEquals(1, kind.delivered(s));

        s.resume();
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3"), all("chunk "), "resume delivers the rest: " + events);
        assertEquals(List.of("chunk 1", "chunk 2", "chunk 3"), chunksOn(test), "on the test thread: " + events);
        assertEquals(List.of("end"), named("end"), "and the end, once: " + events);
        assertEquals(3, kind.delivered(s));
    }

    // H
    @ParameterizedTest
    @EnumSource(Kind.class)
    void theEndHandlerMayHandOffToAnotherThreadThatCallsIntoTheStream(Kind kind) {
        Thread test = Thread.currentThread();
        ReadStream<Buffer> s = kind.create(1);
        AtomicLong seen = new AtomicLong(-1);
        s.endHandler(v -> {
            events.add(new Event("end", Thread.currentThread()));
            handOff("the end handler must not hold the stream's lock", () -> {
                seen.set(kind.delivered(s));
                s.pause();
            });
        });
        s.handler(c -> events.add(new Event("chunk " + kind.label(c), Thread.currentThread())));
        assertEquals(1, seen.get(), "the other thread saw the one chunk counted as delivered");
        assertEquals(List.of("chunk 1"), all("chunk "), "the one chunk, once: " + events);
        assertEquals(List.of("end"), named("end"), "the end fired exactly once: " + events);
        assertSame(test, events.get(indexOf("end")).thread(), "the end on the test thread");
        assertEquals(1, kind.delivered(s));
    }

    // I
    @ParameterizedTest
    @EnumSource(Kind.class)
    void theDrainExitHookRunsAfterTheEndCheckAndTheEndHandler(Kind kind) {
        Thread test = Thread.currentThread();
        ReadStream<Buffer> s = kind.create(1);
        s.endHandler(v -> events.add(new Event("end", Thread.currentThread())));
        kind.beforeDrainExit(s, () -> events.add(new Event("hook", Thread.currentThread())));
        s.handler(c -> events.add(new Event("chunk " + kind.label(c), Thread.currentThread())));
        assertEquals(List.of(new Event("chunk 1", test), new Event("end", test), new Event("hook", test)), events,
                "chunk, then end, then the hook — one loop exit, all on the test thread");
    }

    // J
    @ParameterizedTest
    @EnumSource(Kind.class)
    void aHandlerClearedFromAnotherThreadAsTheDrainLoopExitsStopsDeliveryUntilANewHandlerIsSet(Kind kind) {
        Thread test = Thread.currentThread();
        ReadStream<Buffer> s = kind.create(3);
        s.endHandler(v -> events.add(new Event("end", Thread.currentThread())));
        Window window = new Window(s, "handler(null)+resume", r -> {
            r.handler(null);
            r.resume();
        });
        kind.beforeDrainExit(s, window);
        s.handler(c -> {
            String label = kind.label(c);
            events.add(new Event("chunk " + label, Thread.currentThread()));
            if (label.equals("1")) s.pause();
        });
        window.assertStaged(test);
        assertEquals(List.of("chunk 1"), all("chunk "), "no delivery to a cleared handler: " + events);
        assertEquals(List.of(), named("end"), "no end with chunks left: " + events);
        assertEquals(1, kind.delivered(s));

        s.handler(c -> events.add(new Event("chunk " + kind.label(c), Thread.currentThread())));
        Thread other = window.other.get();
        assertEquals(List.of(new Event("chunk 1", test), new Event("handler(null)+resume returned", other),
                        new Event("chunk 2", test), new Event("chunk 3", test), new Event("end", test)), events,
                "the new handler gets chunks 2 and 3 and the end once, all on the test thread: " + events);
        assertEquals(3, kind.delivered(s));
    }
}
